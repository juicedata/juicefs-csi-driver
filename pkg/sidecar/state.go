type TargetStateRequest struct {
	Pod            *corev1.Pod
	ContainerName  string
	PVC            *corev1.PersistentVolumeClaim
	PV             *corev1.PersistentVolume
	SettingsSecret *corev1.Secret
	CustomerSecret *corev1.Secret
	Node           *corev1.Node
}

type TargetState struct {
	Image string
	Cmd   []string
	IsCE  bool
}

var ErrSettingsSecretMissing = fmt.Errorf("sidecar settings secret not found")

func EffectiveSidecarState(pod *corev1.Pod, container corev1.Container) (string, []string, bool, error) {
	image, cmd, known, err := config.EffectiveSidecarState(pod, container)
	if err != nil || known {
		return image, cmd, known, err
	}
	if len(container.Command) != 3 || container.Command[0] != "sh" || container.Command[1] != "-c" {
		return image, nil, false, nil
	}
	cmd, err = ParseRenderedMountCommand(container.Command[2])
	if err != nil {
		return image, nil, false, nil
	}
	return image, cmd, true, nil
}

func RequiredUpdates(currentImage string, currentCmd []string, cmdKnown bool, target TargetState) (updateBinary, updateArgs bool) {
	updateBinary = currentImage != target.Image
	updateArgs = !target.IsCE && (!cmdKnown || !EqualMountCommands(currentCmd, target.Cmd))
	return
}

// EqualMountCommands reports whether two mount command argvs are equivalent.
// The arguments before "-o" are generated by the builder and never vary, so
// only the comma-joined mount options after "-o" are compared, unordered.
func EqualMountCommands(current, target []string) bool {
	return util.EqualStringLists(mountOptions(current), mountOptions(target))
}

func mountOptions(cmd []string) []string {
	for i, arg := range cmd {
		if arg == "-o" && i+1 < len(cmd) {
			return strings.Split(cmd[i+1], ",")
		}
	}
	return nil
}

// TargetResources contains a point-in-time snapshot of Kubernetes objects used
// to rebuild desired sidecar state without API calls from this package.
type TargetResources struct {
	PVCs    map[string]corev1.PersistentVolumeClaim
	PVs     map[string]corev1.PersistentVolume
	Secrets map[types.NamespacedName]corev1.Secret
	Nodes   map[string]corev1.Node
}

func ResolveTargetStateFromObjects(pod *corev1.Pod, containerName string, resources TargetResources) (TargetState, error) {
	if pod == nil {
		return TargetState{}, fmt.Errorf("pod is required")
	}
	container, err := findContainer(pod, containerName)
	if err != nil {
		return TargetState{}, err
	}
	settingsName := SettingsSecretName(pod, container)
	settingsSecret, ok := resources.Secrets[types.NamespacedName{Namespace: pod.Namespace, Name: settingsName}]
	if settingsName == "" || !ok {
		return TargetState{}, ErrSettingsSecretMissing
	}
	var pvc *corev1.PersistentVolumeClaim
	for _, owner := range settingsSecret.OwnerReferences {
		if owner.Kind == "PersistentVolumeClaim" && owner.Name != "" {
			value, found := resources.PVCs[owner.Name]
			if !found {
				return TargetState{}, fmt.Errorf("PVC %s/%s referenced by sidecar settings secret not found", pod.Namespace, owner.Name)
			}
			pvc = &value
			break
		}
	}
	var pv *corev1.PersistentVolume
	if pvc != nil && pvc.Spec.VolumeName != "" {
		value, found := resources.PVs[pvc.Spec.VolumeName]
		if !found {
			return TargetState{}, fmt.Errorf("PV %s referenced by PVC %s/%s not found", pvc.Spec.VolumeName, pod.Namespace, pvc.Name)
		}
		pv = &value
	}
	var customerSecret *corev1.Secret
	if pv != nil && pv.Spec.CSI != nil && pv.Spec.CSI.NodePublishSecretRef != nil {
		ref := pv.Spec.CSI.NodePublishSecretRef
		value, found := resources.Secrets[types.NamespacedName{Namespace: ref.Namespace, Name: ref.Name}]
		if !found {
			return TargetState{}, fmt.Errorf("customer secret %s/%s referenced by PV %s not found", ref.Namespace, ref.Name, pv.Name)
		}
		customerSecret = &value
	}
	var node *corev1.Node
	if pod.Spec.NodeName != "" {
		if value, found := resources.Nodes[pod.Spec.NodeName]; found {
			node = &value
		}
	}
	return ResolveTargetState(TargetStateRequest{
		Pod: pod, ContainerName: containerName, PVC: pvc, PV: pv,
		SettingsSecret: &settingsSecret, CustomerSecret: customerSecret, Node: node,
	})
}

// ResolveUpgradeTargets computes eligible sidecars from current resources without
// persisting the desired image or command into the upgrade job.
func ResolveUpgradeTargets(pod *corev1.Pod, containerNames []string, resources TargetResources) ([]config.UpgradeTarget, []config.UpgradeTarget, error) {
	if pod == nil {
		return nil, nil, fmt.Errorf("pod is required")
	}
	var eligible, skipped []config.UpgradeTarget
	for _, containerName := range containerNames {
		container, err := findContainer(pod, containerName)
		if err != nil {
			continue
		}
		targetState, err := ResolveTargetStateFromObjects(pod, containerName, resources)
		if err == ErrSettingsSecretMissing {
			continue
		}
		if err != nil {
			return nil, nil, err
		}
		currentImage, currentCmd, known, err := EffectiveSidecarState(pod, *container)
		if err != nil {
			return nil, nil, err
		}
		updateBinary, updateArgs := RequiredUpdates(currentImage, currentCmd, known, targetState)
		target := config.UpgradeTarget{
			Namespace: pod.Namespace, Name: pod.Name, PodUID: pod.UID,
			ContainerName: containerName, Node: pod.Spec.NodeName,
			ContainerID: sidecarContainerID(pod, containerName),
		}
		if updateArgs && !updateBinary && !util.ImageSupportSidecarRestartArgs(container.Image) {
			skipped = append(skipped, target)
		} else if updateBinary || updateArgs {
			eligible = append(eligible, target)
		} else {
			skipped = append(skipped, target)
		}
	}
	return eligible, skipped, nil
}

func SettingsSecretName(pod *corev1.Pod, container *corev1.Container) string {
	for _, vm := range container.VolumeMounts {
		if vm.MountPath != "/jfs-scripts" {
			continue
		}
		for _, vol := range pod.Spec.Volumes {
			if vol.Name != vm.Name || vol.Secret == nil {
				continue
			}
			return vol.Secret.SecretName
		}
		break
	}
	return ""
}

func ResolveTargetState(req TargetStateRequest) (TargetState, error) {
	if req.Pod == nil || req.ContainerName == "" || req.SettingsSecret == nil {
		return TargetState{}, ErrSettingsSecretMissing
	}
	container, err := findContainer(req.Pod, req.ContainerName)
	if err != nil {
		return TargetState{}, err
	}
	mountPath, _, err := util.GetMountPathOfSidecar(*req.Pod, req.ContainerName)
	if err != nil {
		return TargetState{}, err
	}
	// Load the persisted setting if present; otherwise start from a minimal
	// setting populated with the resolved request inputs so the existing
	// builder can still produce a mount command.
	var setting *config.JfsSetting
	if raw := req.SettingsSecret.Data["jfsSettings"]; len(raw) > 0 {
		setting, err = config.RevertSettingWithNode(req.Pod, req.PVC, req.PV, req.SettingsSecret, req.CustomerSecret, req.Node)
		if err != nil {
			return TargetState{}, err
		}
	} else {
		return TargetState{}, ErrSettingsSecretMissing
	}
	setting.AppPod = req.Pod
	setting.Node = req.Node
	if err := setting.ReNewWithMountPath(req.Pod, req.PVC, req.PV, req.CustomerSecret, mountPath); err != nil {
		return TargetState{}, err
	}
	renderSetting, err := cloneSetting(setting)
	if err != nil {
		return TargetState{}, err
	}

	capacity := int64(0)
	if req.PVC != nil && (config.GlobalConfig.EnableSetQuota == nil || *config.GlobalConfig.EnableSetQuota) {
		capacity = req.PVC.Spec.Resources.Requests.Storage().Value() / 1024 / 1024 / 1024
	}
	var renderer builder.SidecarInterface
	if !isServerless(container) {
		renderer = builder.NewContainerBuilder(renderSetting, capacity)
	} else if req.PVC == nil {
		return TargetState{}, fmt.Errorf("PVC is required for serverless sidecar")
	} else if req.Pod.Annotations[builder.VCIANNOKey] == builder.VCIANNOValue {
		renderer = builder.NewVCIBuilder(renderSetting, capacity, *req.Pod, *req.PVC)
	} else if req.Pod.Labels[builder.CCIANNOKey] == builder.CCIANNOValue {
		renderer = builder.NewCCIBuilder(renderSetting, capacity, *req.Pod, *req.PVC)
	} else {
		renderer = builder.NewServerlessBuilder(renderSetting, capacity, *req.Pod, *req.PVC)
	}

	rendered := renderer.NewMountSidecar()
	if rendered == nil || len(rendered.Spec.Containers) == 0 || len(rendered.Spec.Containers[0].Command) < 3 {
		return TargetState{}, fmt.Errorf("builder returned no rendered mount command")
	}
	if renderSetting.IsCe {
		return TargetState{Image: rendered.Spec.Containers[0].Image, IsCE: true}, nil
	}
	cmd, err := ParseRenderedMountCommand(rendered.Spec.Containers[0].Command[2])
	if err != nil {
		return TargetState{}, err
	}
	return TargetState{
		Image: rendered.Spec.Containers[0].Image,
		Cmd:   cmd,
		IsCE:  renderSetting.IsCe,
	}, nil
}

func findContainer(pod *corev1.Pod, name string) (*corev1.Container, error) {
	for i := range pod.Spec.Containers {
		if pod.Spec.Containers[i].Name == name {
			return &pod.Spec.Containers[i], nil
		}
	}
	for i := range pod.Spec.InitContainers {
		if pod.Spec.InitContainers[i].Name == name {
			return &pod.Spec.InitContainers[i], nil
		}
	}
	return nil, fmt.Errorf("container %s not found in pod %s/%s", name, pod.Namespace, pod.Name)
}

func isServerless(container *corev1.Container) bool {
	for _, env := range container.Env {
		if env.Name == "JFS_NO_UMOUNT" && env.Value == "1" {
			return true
		}
	}
	return false
}

func sidecarContainerID(pod *corev1.Pod, name string) string {
	if pod == nil {
		return ""
	}
	for _, status := range pod.Status.ContainerStatuses {
		if status.Name == name {
			return status.ContainerID
		}
	}
	for _, status := range pod.Status.InitContainerStatuses {
		if status.Name == name {
			return status.ContainerID
		}
	}
	return ""
}

func cloneSetting(setting *config.JfsSetting) (*config.JfsSetting, error) {
	raw, err := json.Marshal(setting)
	if err != nil {
		return nil, err
	}
	clone := &config.JfsSetting{}
	if err := json.Unmarshal(raw, clone); err != nil {
		return nil, err
	}
	clone.PV, clone.PVC, clone.Node, clone.AppPod = setting.PV, setting.PVC, setting.Node, setting.AppPod
	clone.CustomerSecret, clone.JuiceFSSecret = setting.CustomerSecret, setting.JuiceFSSecret
	return clone, nil
}
